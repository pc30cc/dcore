/**
 * The templates this build ships, `neon` (dark) and `white` (light): every
 * token of the template contract, token for token. `TemplateTokensTest`
 * checks that each defines the whole contract and dumps the values for an
 * outside comparison.
 *
 * The accent follows the brand: with the brand's own colours (brand.json
 * `colors`) the accent group is drawn from them ([NeonAccent], [WhiteAccent]),
 * kept to the template's contrast rules; a brand that keeps the design's
 * colours gets the design's values exactly.
 */
object Templates {
    const val NEON: String = "neon"
    const val WHITE: String = "white"

    /** The ids this build can draw, in display order. */
    val ids: List<String> = listOf(NEON, WHITE)

    /** `neon` in the design's own colours. */
    val Neon: AppTemplate by lazy { neon(NeonAccent.Design) }

    /** `white` in the design's own colours. */
    val White: AppTemplate by lazy { white(WhiteAccent.Design) }

    private val branded = ConcurrentHashMap<Pair<String, BrandColors>, AppTemplate>()

    /** The template [id] in [brand]'s colours (this build's brand by default); `neon` for an id this build does not ship. */
    fun of(id: String, brand: BrandColors = BrandColors.Build): AppTemplate = when (id) {
        WHITE -> if (WhiteAccent.isDesign(brand)) White else branded.getOrPut(WHITE to brand) { white(WhiteAccent.of(brand)) }
        else -> if (NeonAccent.isDesign(brand)) Neon else branded.getOrPut(NEON to brand) { neon(NeonAccent.of(brand)) }
    }

    /** Neon's slider and progress track (`--slider-track`, `--progress-track`). */
    private val NEON_TRACK = Color(0xFF272331)

    /**
     * [c] lightened just enough to read 3:1 on neon's track (WCAG 1.4.11):
     * the fill is the only cue of how far a slider or the onboarding bar
     * has gone. The design's violet stop (#7B2BFF, 2.65:1) becomes #8141FF (3.01:1).
     */
    private fun onNeonTrack(c: Color): Color = Contrast.ensure(c, listOf(NEON_TRACK), Contrast.AA_LARGE, Color.White)

    /** `neon` in [accent] (its "yes" gradient, the brand's stops). */
