-- ─── store_products ───────────────────────────────────────────────────────
-- The mapping from a store's product to what it grants. Product ids are
-- neutral and the same in both stores (android ProductIds); each
-- store has its own rows because prices, offers and state differ
-- completely. Play subscriptions need a base plan id; Cafe Bazaar has none
-- (one SKU per period). Bazaar's developer API returns no price (the client
-- only gets a formatted string), so list_price_* is the panel's copy: each
-- Bazaar event copies the price of the moment into store_events as an
-- estimate, so a later price edit never rewrites past revenue.
CREATE TABLE store_products (
  id                smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  updated_at        timestamptz NOT NULL DEFAULT now(),
  list_price_minor  bigint      CHECK (list_price_minor >= 0),
  store             smallint    NOT NULL CHECK (store BETWEEN 1 AND 3),
  kind              smallint    NOT NULL CHECK (kind BETWEEN 1 AND 2),
  plan_id           smallint    REFERENCES plans (id),
  grant_item        smallint    CHECK (grant_item BETWEEN 1 AND 4),
  grant_qty         smallint    CHECK (grant_qty BETWEEN 1 AND 1000),
  sort              smallint    NOT NULL DEFAULT 0,
  badge             smallint    NOT NULL DEFAULT 0 CHECK (badge BETWEEN 0 AND 3),
  is_active         boolean     NOT NULL DEFAULT false,
  list_currency     char(3)     CHECK (list_currency ~ '^[A-Z]{3}$'),
  product_id        text        NOT NULL CHECK (product_id ~ '^[a-z0-9][a-z0-9._]{0,98}$'),
  base_plan_id      text        CHECK (base_plan_id ~ '^[a-z0-9][a-z0-9-]{0,62}$'),
  period            text        CHECK (period ~ '^P[1-9][0-9]?[DWMY]$'),
  CONSTRAINT store_products_key UNIQUE NULLS NOT DISTINCT (store, product_id, base_plan_id),
  CONSTRAINT store_products_kind CHECK (
    (kind = 1 AND plan_id IS NOT NULL AND period IS NOT NULL AND grant_item IS NULL AND grant_qty IS NULL)
    OR (kind = 2 AND plan_id IS NULL AND period IS NULL AND base_plan_id IS NULL
        AND grant_item IS NOT NULL AND grant_qty IS NOT NULL)),
  CONSTRAINT store_products_price CHECK ((list_price_minor IS NULL) = (list_currency IS NULL)),
  CONSTRAINT store_products_bazaar_no_base_plan CHECK (store <> 2 OR base_plan_id IS NULL)
);

COMMENT ON TABLE store_products IS
  'kind: 1 auto-renewing subscription (plan_id, ISO 8601 period), 2 consumable (grant_item x grant_qty into the wallet). grant_item: 1 super like, 2 boost, 3 spotlight, 4 direct message. badge: 0 none, 1 most popular, 2 best value, 3 new. Seeded inactive: the panel turns a row on once the product exists in that store''s console.';

