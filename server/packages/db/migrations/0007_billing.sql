-- ─── store_purchases ──────────────────────────────────────────────────────
-- One row per purchase token, in either store. The token is what the
-- server sends back to the store's API (Play: subscriptionsv2.get,
-- acknowledge, consume; Bazaar: the validate endpoints); token_hash
-- (SHA-256) is the lookup key, so a long token is never indexed.
-- A row is rewritten only when the verified state changes.
-- next_check_at: when the worker must ask the store again. Play pushes RTDN,
-- so for Play it is the expiry plus a margin (a missed notification);
-- Cafe Bazaar sends no server notification, so every Bazaar subscription is
-- re-validated at its validUntil, which is how renewals, cancellations and
-- expiries are learnt.
CREATE TABLE store_purchases (
  id                 bigint      PRIMARY KEY,
  user_id            bigint      REFERENCES users (id),
  purchased_at       timestamptz NOT NULL,
  expires_at         timestamptz,
  acknowledged_at    timestamptz,
  consumed_at        timestamptz,
  credited_at        timestamptz,
  next_check_at      timestamptz,
  updated_at         timestamptz NOT NULL DEFAULT now(),
  last_event_ms      bigint,
  product_ref        smallint    NOT NULL REFERENCES store_products (id),
  store              smallint    NOT NULL CHECK (store BETWEEN 1 AND 3),
  kind               smallint    NOT NULL CHECK (kind BETWEEN 1 AND 2),
  state              smallint    NOT NULL CHECK (state BETWEEN 1 AND 12),
  quantity           smallint    NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 100),
  auto_renew         boolean,
  is_test            boolean     NOT NULL DEFAULT false,
  region             char(2)     CHECK (region ~ '^[A-Z]{2}$'),
  token_hash         bytea       NOT NULL CHECK (octet_length(token_hash) = 32),
  linked_token_hash  bytea       CHECK (octet_length(linked_token_hash) = 32),
  token              text        NOT NULL CHECK (char_length(token) BETWEEN 8 AND 4096),
  order_id           text        CHECK (char_length(order_id) <= 200),
  CONSTRAINT store_purchases_token_key UNIQUE (store, token_hash),
  CONSTRAINT store_purchases_attributed CHECK (state = 11 OR user_id IS NOT NULL),
  CONSTRAINT store_purchases_subscription CHECK (kind = 2 OR expires_at IS NOT NULL OR state IN (1, 11))
) WITH (fillfactor = 90);

COMMENT ON TABLE store_purchases IS
  'state: 1 pending (paid later; grants nothing), 2 active, 3 canceled (auto-renew off, access until expires_at), 4 in grace period (access), 5 on hold (no access), 6 paused (no access), 7 expired, 8 revoked/refunded (access ends now), 9 replaced by a linked token (upgrade, downgrade), 10 consumed (consumable credited and consumed), 11 unclaimed (no account could be attributed yet), 12 purchased (consumable verified, not yet consumed). linked_token_hash: Play linkedPurchaseToken. last_event_ms: newest store event applied (older RTDN for the same token are ignored). Account binding: Play obfuscatedAccountId / Bazaar developer payload = the account''s billing reference (a keyed permutation of user_id), checked on every verification.';

-- "My purchases", restore, the user's page in the panel.
CREATE INDEX store_purchases_user_idx ON store_purchases (user_id) WHERE user_id IS NOT NULL;
-- Search by the store's order id (panel) and matching voided/refunded orders.
CREATE INDEX store_purchases_order_idx ON store_purchases (store, order_id) WHERE order_id IS NOT NULL;
-- The daily safety sweep behind the per-purchase delayed re-check jobs.
CREATE INDEX store_purchases_check_idx ON store_purchases (next_check_at) WHERE next_check_at IS NOT NULL;

-- ─── store_events ─────────────────────────────────────────────────────────
-- Append-only: one row per state change actually applied (not per incoming
-- notification: those are de-duplicated in Valkey and the raw payload is not
-- stored). Revenue reports and the purchase timeline read it. Small (one row
-- per purchase change) and never deleted (financial records), so it is an
-- ordinary table: a partition per month would only add relations for the
-- timeline lookup to probe. Written in the same transaction as the purchase
-- change. Bazaar returns no price: its events carry the product's list price
-- at that moment with amount_estimated set.
CREATE TABLE store_events (
  id                bigint      PRIMARY KEY,
  purchase_id       bigint      NOT NULL REFERENCES store_purchases (id),
  user_id           bigint      REFERENCES users (id),
  occurred_at       timestamptz NOT NULL,
  expires_at        timestamptz,
  amount_micros     bigint,
  store             smallint    NOT NULL CHECK (store BETWEEN 1 AND 3),
  event             smallint    NOT NULL CHECK (event BETWEEN 1 AND 99),
  source            smallint    NOT NULL CHECK (source BETWEEN 1 AND 7),
  state_from        smallint    CHECK (state_from BETWEEN 1 AND 12),
  state_to          smallint    NOT NULL CHECK (state_to BETWEEN 1 AND 12),
  amount_estimated  boolean     NOT NULL DEFAULT false,
  currency          char(3)     CHECK (currency ~ '^[A-Z]{3}$'),
  order_id          text        CHECK (char_length(order_id) <= 200),
  CONSTRAINT store_events_amount CHECK ((amount_micros IS NULL) = (currency IS NULL)),
  CONSTRAINT store_events_estimate CHECK (NOT amount_estimated OR amount_micros IS NOT NULL)
);

COMMENT ON TABLE store_events IS
  'event: 1 verified, 2 renewed, 3 auto-renew off, 4 auto-renew on/restarted, 5 grace, 6 on hold, 7 recovered, 8 paused, 9 expired, 10 revoked or refunded, 11 replaced, 12 acknowledged, 13 consumed, 14 credited, 99 other. source: 1 app (POST purchase), 2 Play RTDN, 3 scheduled re-check, 4 Play voided purchases list, 5 admin, 6 restore, 7 Bazaar validation. amount_estimated: the amount is the catalogue''s list price at the time (Bazaar), not a price the store reported.';

-- The purchase timeline in the panel.
CREATE INDEX store_events_purchase_idx ON store_events (purchase_id, id);

-- ─── subscriptions ────────────────────────────────────────────────────────
-- The computed result per user and source: which plan applies now and until
-- when, one row per store the user pays in (store 0 = admin grants).
-- Recomputed after any purchase change or grant, rewritten only when the
-- result differs; deleted when it ends (no row = free). A session's plan is
-- the best of its own store's row and store 0, or of every row when
-- billing.cross_store_entitlements is on; cached in Valkey per store.
CREATE TABLE subscriptions (
  user_id      bigint      NOT NULL REFERENCES users (id),
  started_at   timestamptz NOT NULL,
  expires_at   timestamptz NOT NULL,
  updated_at   timestamptz NOT NULL DEFAULT now(),
  purchase_id  bigint      REFERENCES store_purchases (id),
  plan_id      smallint    NOT NULL REFERENCES plans (id),
  store        smallint    NOT NULL CHECK (store BETWEEN 0 AND 3),
  status       smallint    NOT NULL CHECK (status BETWEEN 1 AND 4),
  auto_renew   boolean     NOT NULL DEFAULT false,
  PRIMARY KEY (user_id, store),
  CONSTRAINT subscriptions_source CHECK ((store = 0) = (purchase_id IS NULL))
) WITH (fillfactor = 90);

COMMENT ON TABLE subscriptions IS
  'store: 0 = admin grants, else the store of purchase_id. status: 1 active and renewing, 2 active until expires_at (renewal off), 3 grace period, 4 granted. An expired subscription is deleted; history is in store_purchases and store_events.';

-- The daily safety sweep behind the delayed "subscription ends" job.
CREATE INDEX subscriptions_expires_idx ON subscriptions (expires_at);

CREATE TABLE entitlement_grants (
  id          bigint      PRIMARY KEY,
  user_id     bigint      NOT NULL REFERENCES users (id),
  starts_at   timestamptz NOT NULL,
  ends_at     timestamptz NOT NULL,
  revoked_at  timestamptz,
  granted_by  integer     REFERENCES admin_users (id),
  plan_id     smallint    NOT NULL REFERENCES plans (id),
  reason      text        NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 500),
  CONSTRAINT entitlement_grants_period CHECK (ends_at > starts_at)
);

COMMENT ON TABLE entitlement_grants IS 'Days of a plan given in the panel (support gesture, referral reward). Not money: never a store purchase.';

CREATE INDEX entitlement_grants_user_idx ON entitlement_grants (user_id);

-- ─── wallet ───────────────────────────────────────────────────────────────
-- Bought or gifted consumables. Free daily/weekly quotas are counters in
-- Valkey; only what was paid for or given lives here. Balances are kept per
-- source store (0 = gifts, rewards and allowances): with
-- billing.cross_store_entitlements off a session spends its own store's
-- balance and then store 0, with it on any balance. A use is one
-- transaction: UPDATE wallet_balances ... WHERE balance >= 1 RETURNING, then
-- INSERT INTO wallet_ledger.
CREATE TABLE wallet_balances (
  user_id     bigint      NOT NULL REFERENCES users (id),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  balance     integer     NOT NULL DEFAULT 0 CHECK (balance >= 0),
  item        smallint    NOT NULL CHECK (item BETWEEN 1 AND 4),
  store       smallint    NOT NULL DEFAULT 0 CHECK (store BETWEEN 0 AND 3),
  PRIMARY KEY (user_id, item, store)
) WITH (fillfactor = 80);

CREATE TABLE wallet_ledger (
  id             bigint   PRIMARY KEY,
  user_id        bigint   NOT NULL REFERENCES users (id),
  ref_id         bigint,
  delta          integer  NOT NULL CHECK (delta <> 0),
  balance_after  integer  NOT NULL CHECK (balance_after >= 0),
  admin_id       integer  REFERENCES admin_users (id),
  item           smallint NOT NULL CHECK (item BETWEEN 1 AND 4),
  store          smallint NOT NULL DEFAULT 0 CHECK (store BETWEEN 0 AND 3),
  reason         smallint NOT NULL CHECK (reason BETWEEN 1 AND 9)
);

COMMENT ON TABLE wallet_ledger IS
  'Append-only. item: 1 super like, 2 boost, 3 spotlight, 4 direct message. store: the balance moved (as wallet_balances.store). reason: 1 purchase credit (ref = store_purchases.id), 2 use (ref = like/boost id), 3 refund reversal (ref = store_purchases.id; never below zero, the shortfall is noted in the panel), 4 admin gift, 5 referral reward, 6 plan allowance, 7 expiry, 8 admin correction, 9 restored. Time = id_time(id).';

CREATE INDEX wallet_ledger_user_idx ON wallet_ledger (user_id, id);
-- A purchase is credited once and reversed once, whatever retries happen.
CREATE UNIQUE INDEX wallet_ledger_once_idx ON wallet_ledger (reason, ref_id) WHERE reason IN (1, 3);
