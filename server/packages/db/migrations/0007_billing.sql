-- 0007 - Billing: plans and their features, store products for Google Play
-- and Cafe Bazaar, verified store purchases, their state-change events, the
-- computed subscription per user and store, admin grants, and the
-- consumables wallet.
--
-- Every write here is synchronous and transactional (money). Volume is low:
-- roughly one row change per purchase, renewal, refund or consumable use.
-- Request paths read entitlements from Valkey (`ent:<user>:<store>`), rebuilt from
-- these tables only after a change.
--
-- Store codes (also devices.store): 1 google_play, 2 cafe_bazaar,
-- 3 app_store (reserved for iOS).

-- ─── plans and features ───────────────────────────────────────────────────
CREATE TABLE plans (
  id          smallint    PRIMARY KEY,
  updated_at  timestamptz NOT NULL DEFAULT now(),
  rank        smallint    NOT NULL UNIQUE CHECK (rank >= 0),
  sort        smallint    NOT NULL DEFAULT 0,
  is_active   boolean     NOT NULL DEFAULT true,
  key         text        NOT NULL UNIQUE CHECK (key ~ '^[a-z][a-z0-9_]{1,31}$'),
  names       jsonb       NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(names) = 'object')
);

COMMENT ON TABLE plans IS
  'Tiers. Keys are neutral (free, plus, premium); the names people see come from the active brand (brands.config planNames) and fall back to names here. rank orders upgrades.';

-- A feature value is a JSON number (a quota; -1 = unlimited) or boolean.
CREATE TABLE plan_features (
  plan_id  smallint NOT NULL REFERENCES plans (id) ON DELETE CASCADE,
  feature  text     NOT NULL CHECK (feature ~ '^[a-z][a-z0-9_]{1,47}$'),
  value    jsonb    NOT NULL CHECK (jsonb_typeof(value) IN ('number', 'boolean')),
  PRIMARY KEY (plan_id, feature)
);

