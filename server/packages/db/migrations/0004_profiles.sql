-- 0004 - Profiles: the field catalog, profile content, photos, prompts,
-- search preferences, location (fuzzed cells only) and face verification.
--
-- All of these change only when a person edits something, so they carry
-- ordinary foreign keys and few indexes. The discovery index that the deck
-- reads is derived from them (0006_discovery.sql); the card a viewer sees is
-- cached in Valkey under the profile's version.

-- ─── Catalogs edited in the admin panel ───────────────────────────────────
CREATE TABLE profile_field_defs (
  id                smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  updated_at        timestamptz NOT NULL DEFAULT now(),
  updated_by        integer     REFERENCES admin_users (id),
  type              smallint    NOT NULL CHECK (type BETWEEN 1 AND 5),
  sort              smallint    NOT NULL DEFAULT 0,
  filter_slot       smallint    UNIQUE CHECK (filter_slot BETWEEN 1 AND 127),
  max_choices       smallint    CHECK (max_choices BETWEEN 1 AND 30),
  is_active         boolean     NOT NULL DEFAULT true,
  is_required       boolean     NOT NULL DEFAULT false,
  is_public         boolean     NOT NULL DEFAULT true,
  is_filterable     boolean     NOT NULL DEFAULT false,
  is_premium_filter boolean     NOT NULL DEFAULT false,
  is_sensitive      boolean     NOT NULL DEFAULT false,
  key               text        NOT NULL UNIQUE CHECK (key ~ '^[a-z][a-z0-9_]{1,39}$'),
  discovery_column  text        CHECK (discovery_column IN ('height_cm')),
  i18n              jsonb       NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(i18n) = 'object'),
  options           jsonb       CHECK (options IS NULL OR jsonb_typeof(options) = 'array'),
  CONSTRAINT profile_field_defs_options CHECK ((type IN (1, 2)) = (options IS NOT NULL)),
  CONSTRAINT profile_field_defs_slot CHECK (filter_slot IS NULL OR (type IN (1, 2) AND is_filterable)),
  CONSTRAINT profile_field_defs_column CHECK (discovery_column IS NULL OR (type = 4 AND is_filterable)),
  CONSTRAINT profile_field_defs_choices CHECK ((type = 2) = (max_choices IS NOT NULL))
);

COMMENT ON TABLE profile_field_defs IS
  'The panel''s field catalog. type: 1 single choice, 2 multiple choice, 3 short text, 4 number, 5 country. options: [{"id": 1-255, "i18n": {...}, "active": true}]; an option id is never reused. filter_slot: a filterable choice field''s options are copied into discovery.attrs as slot * 256 + option id. discovery_column: a filterable number copied to that discovery column. is_sensitive: a GDPR special category (religion, ...), stored only with explicit consent (user_consents kind 4) and never readable by the analytics role. A change here does not touch the people who use the field: the admin route bumps the catalogue version (part of the card cache key) and enqueues discovery_resync() over the discovery table.';

CREATE TABLE prompt_defs (
  id          smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  updated_at  timestamptz NOT NULL DEFAULT now(),
  kind        smallint    NOT NULL DEFAULT 1 CHECK (kind BETWEEN 1 AND 2),
  sort        smallint    NOT NULL DEFAULT 0,
  is_active   boolean     NOT NULL DEFAULT true,
  i18n        jsonb       NOT NULL CHECK (jsonb_typeof(i18n) = 'object')
);

COMMENT ON TABLE prompt_defs IS 'kind: 1 text answer, 2 voice answer (P1).';

-- ─── profiles ─────────────────────────────────────────────────────────────
-- What other people see, plus the person's own privacy switches. `version` is
-- bumped by every change the card carries (here, photos, prompts, field
-- values, and the hide_age, hide_distance and show_online switches: see
-- 0006) and names the cached card (`card:<id>:<version>:<catalogue>`), so an
-- edit never needs a cache purge. accept_calls is the default for new
-- matches; turning it off also clears the person's call bit in every active
-- match (matches.flags), which is what call placement reads.
CREATE TABLE profiles (
  user_id       bigint      PRIMARY KEY REFERENCES users (id),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  version       integer     NOT NULL DEFAULT 1 CHECK (version > 0),
  intention     smallint    CHECK (intention BETWEEN 1 AND 4),
  completeness  smallint    NOT NULL DEFAULT 0 CHECK (completeness BETWEEN 0 AND 100),
  text_state    smallint    NOT NULL DEFAULT 1 CHECK (text_state BETWEEN 1 AND 3),
  mode_match    boolean     NOT NULL DEFAULT true,
  mode_social   boolean     NOT NULL DEFAULT false,
  incognito     boolean     NOT NULL DEFAULT false,
  hide_age      boolean     NOT NULL DEFAULT false,
  hide_distance boolean     NOT NULL DEFAULT false,
  show_online   boolean     NOT NULL DEFAULT true,
  accept_calls  boolean     NOT NULL DEFAULT true,
  display_name  text        NOT NULL CHECK (char_length(display_name) BETWEEN 1 AND 40),
  about         text        CHECK (char_length(about) <= 500),
  job_title     text        CHECK (char_length(job_title) <= 80)
) WITH (fillfactor = 90);

COMMENT ON TABLE profiles IS
  'intention: 1 serious relationship, 2 marriage, 3 friendship, 4 not sure. text_state (automatic + human text moderation): 1 checking, 2 approved, 3 rejected. mode_match: the person takes part in the deck (discovery).';

CREATE TABLE profile_field_values (
  user_id   bigint   NOT NULL REFERENCES users (id),
  field_id  smallint NOT NULL REFERENCES profile_field_defs (id),
  num       integer,
  opt       smallint CHECK (opt BETWEEN 1 AND 255),
  opts      smallint[] CHECK (cardinality(opts) BETWEEN 1 AND 30 AND array_ndims(opts) = 1),
  txt       text     CHECK (char_length(txt) BETWEEN 1 AND 200),
  PRIMARY KEY (user_id, field_id),
  CONSTRAINT profile_field_values_one_value CHECK (num_nonnulls(num, opt, opts, txt) = 1)
);

COMMENT ON TABLE profile_field_values IS
  'One typed value per (user, field): opt for single choice, opts for multiple choice, num for numbers, txt for text and country codes. The API validates option ids against the catalog.';

-- ─── photos ───────────────────────────────────────────────────────────────
-- Up to 9 per user (position 0-8). Blobs live in object storage under a path
-- derived from (id, blob_ver); nothing public until status = 3.
CREATE TABLE photos (
  id             bigint      PRIMARY KEY,
  user_id        bigint      NOT NULL REFERENCES users (id),
  decided_at     timestamptz,
  phash          bigint,
  decided_by     integer     REFERENCES admin_users (id),
  width          smallint    CHECK (width > 0),
  height         smallint    CHECK (height > 0),
  position       smallint    NOT NULL CHECK (position BETWEEN 0 AND 8),
  status         smallint    NOT NULL DEFAULT 1 CHECK (status BETWEEN 1 AND 4),
  reject_reason  smallint    CHECK (reject_reason BETWEEN 1 AND 30),
  mod_flags      smallint    NOT NULL DEFAULT 0 CHECK (mod_flags >= 0),
  blob_ver       smallint    NOT NULL DEFAULT 1 CHECK (blob_ver > 0),
  has_face       boolean,
  blurhash       text        CHECK (char_length(blurhash) <= 64),
  -- Deferrable so a reorder can swap positions in one transaction
  -- (SET CONSTRAINTS photos_user_position_key DEFERRED).
  CONSTRAINT photos_user_position_key UNIQUE (user_id, position) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT photos_rejected CHECK ((status = 4) = (reject_reason IS NOT NULL))
);

COMMENT ON TABLE photos IS
  'status: 1 processing (EXIF/GPS stripped, variants, automatic checks), 2 waiting for a human, 3 approved (public), 4 rejected (reason shown to the uploader). mod_flags: automatic labels bitmask (1 nudity, 2 violence, 4 text, 8 possible minor, 16 no face, 32 duplicate/stolen). phash: 64-bit perceptual hash.';

-- The human review queue.
CREATE INDEX photos_review_queue_idx ON photos (id) WHERE status = 2;

-- Near-duplicate search (stolen or reused pictures, re-encoded, resized or
-- slightly cropped). The 64-bit hash is cut into four 16-bit bands, each
-- tagged with its band number; two hashes within 3 bits of each other share
-- at least one band (pigeonhole), so one GIN probe on the bands finds every
-- candidate, and the Hamming distance is checked on those rows:
--   WHERE phash IS NOT NULL AND phash_bands(phash) && phash_bands($1)
--     AND bit_count(int8send(phash # $1)) <= 3
CREATE FUNCTION phash_bands(p_hash bigint) RETURNS integer[]
  LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
  RETURN ARRAY[(p_hash & 65535)::integer,
               (1 << 16) | ((p_hash >> 16) & 65535)::integer,
               (2 << 16) | ((p_hash >> 32) & 65535)::integer,
               (3 << 16) | ((p_hash >> 48) & 65535)::integer];

CREATE INDEX photos_phash_bands_idx ON photos USING gin (phash_bands(phash)) WHERE phash IS NOT NULL;

CREATE TABLE profile_prompts (
  user_id    bigint   NOT NULL REFERENCES users (id),
  position   smallint NOT NULL CHECK (position BETWEEN 0 AND 2),
  prompt_id  smallint NOT NULL REFERENCES prompt_defs (id),
  status     smallint NOT NULL DEFAULT 1 CHECK (status BETWEEN 1 AND 3),
  audio_ms   integer  CHECK (audio_ms BETWEEN 1 AND 60000),
  answer     text     CHECK (char_length(answer) BETWEEN 1 AND 300),
  PRIMARY KEY (user_id, position),
  CONSTRAINT profile_prompts_once UNIQUE (user_id, prompt_id),
  CONSTRAINT profile_prompts_answer CHECK (answer IS NOT NULL OR audio_ms IS NOT NULL)
);

COMMENT ON TABLE profile_prompts IS 'status: 1 checking, 2 approved, 3 rejected (same moderation as profile text).';

-- ─── preferences ──────────────────────────────────────────────────────────
CREATE TABLE preferences (
  user_id          bigint      PRIMARY KEY REFERENCES users (id),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  max_distance_km  smallint    NOT NULL DEFAULT 50 CHECK (max_distance_km BETWEEN 1 AND 500),
  age_min          smallint    NOT NULL DEFAULT 18 CHECK (age_min BETWEEN 18 AND 99),
  age_max          smallint    NOT NULL DEFAULT 99 CHECK (age_max BETWEEN 18 AND 99),
  interested_in    smallint    NOT NULL CHECK (interested_in BETWEEN 2 AND 14 AND (interested_in & 1) = 0),
  intents          smallint    NOT NULL DEFAULT 0 CHECK (intents BETWEEN 0 AND 30 AND (intents & 1) = 0),
  flags            smallint    NOT NULL DEFAULT 0 CHECK (flags BETWEEN 0 AND 3),
  filters          jsonb       NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(filters) = 'object'),
  CONSTRAINT preferences_age_range CHECK (age_min <= age_max)
);

COMMENT ON TABLE preferences IS
  'interested_in: bitmask of gender codes (1 << gender: 2 women, 4 men, 8 non-binary). intents: bitmask of intention codes (1 << intention), 0 = any. flags: 1 whole country (no distance), 2 verified profiles only. filters: advanced (premium) filters {"<field key>": [option ids], "height_cm": [min, max]}, applied by the deck worker. Changes of max_distance_km are rate-limited by the API (repeated radius changes are how distances are probed).';

-- ─── user_locations ───────────────────────────────────────────────────────
-- Exact coordinates are never stored: the API turns the phone's position
-- into an H3 resolution-7 cell (average edge 1.4 km, area 5.2 km2) in memory
-- and keeps only the cell and the cell's centre. Distances shown to others
-- and the radius cut are computed from cell centres, so the most anyone can
-- learn about a person's position, even by probing from many points, is
-- their r7 cell. A row is written only when the cell changes.
CREATE TABLE user_locations (
  user_id         bigint      PRIMARY KEY REFERENCES users (id),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  travel_until    timestamptz,
  home_h3         bigint      NOT NULL CHECK (h3_is_cell(home_h3) AND h3_resolution(home_h3) = 7),
  travel_h3       bigint      CHECK (h3_is_cell(travel_h3) AND h3_resolution(travel_h3) = 7),
  home_city_id    integer,
  travel_city_id  integer,
  source          smallint    NOT NULL CHECK (source BETWEEN 1 AND 3),
  country         char(2)     NOT NULL CHECK (country ~ '^[A-Z]{2}$'),
  travel_country  char(2)     CHECK (travel_country ~ '^[A-Z]{2}$'),
  home_geo        geography(Point, 4326) NOT NULL,
  travel_geo      geography(Point, 4326),
  CONSTRAINT user_locations_travel CHECK (num_nulls(travel_until, travel_h3, travel_geo, travel_country) IN (0, 4))
) WITH (fillfactor = 90);

COMMENT ON TABLE user_locations IS
  'Fuzzed location: H3 r7 cells and their centres only, never the phone''s coordinates. source: 1 GPS (cell of the fix), 2 city chosen by hand, 3 country from the network. city ids are GeoNames ids resolved by the API from a bundled dataset (no FK). Travel (premium) replaces home until travel_until.';

-- ─── verifications ────────────────────────────────────────────────────────
-- Selfie liveness checks. The selfie and video are kept only until
-- media_purge_at (30 days after the decision by default); the row keeps the
-- outcome. photo_id is the profile photo the selfie was compared with (the
-- one at position 0 when the check started): the badge holds only while that
-- photo is approved and still the main one (verification_reference_check).
CREATE TABLE verifications (
  id              bigint      PRIMARY KEY,
  user_id         bigint      NOT NULL REFERENCES users (id),
  photo_id        bigint      REFERENCES photos (id) ON DELETE SET NULL,
  decided_at      timestamptz,
  media_purge_at  timestamptz,
  reviewed_by     integer     REFERENCES admin_users (id),
  method          smallint    NOT NULL DEFAULT 1 CHECK (method BETWEEN 1 AND 2),
  status          smallint    NOT NULL DEFAULT 1 CHECK (status BETWEEN 1 AND 6),
  score           smallint    CHECK (score BETWEEN 0 AND 1000),
  reject_reason   smallint    CHECK (reject_reason BETWEEN 1 AND 30),
  provider_ref    text        CHECK (char_length(provider_ref) <= 200),
  CONSTRAINT verifications_decided CHECK ((status IN (3, 4, 6)) = (decided_at IS NOT NULL))
);

COMMENT ON TABLE verifications IS
  'method: 1 selfie liveness, 2 video selfie. status: 1 started, 2 waiting for a human, 3 approved, 4 rejected, 5 expired, 6 lapsed (the reference photo left position 0, was rejected or deleted: verify again). score: provider similarity x 1000. A revocation by an admin is a moderation action (kind 8); a lapse is recorded here.';

CREATE INDEX verifications_user_idx ON verifications (user_id, id);
CREATE INDEX verifications_review_queue_idx ON verifications (id) WHERE status = 2;
CREATE INDEX verifications_media_purge_idx ON verifications (media_purge_at) WHERE media_purge_at IS NOT NULL;

-- After a reorder, a moderation decision or a delete of photos: a person's
-- newest approved verification lapses when its reference photo is no longer
-- the approved photo at position 0, and the badge goes with it (users
-- triggers in 0006 then bump the card version and re-sync discovery). One
-- run per statement over the people the statement touched.
CREATE FUNCTION verification_reference_check() RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = public, pg_temp
AS $$
BEGIN
  WITH touched AS (
    SELECT DISTINCT o.user_id FROM old_rows o
  ), latest AS (
    SELECT DISTINCT ON (v.user_id) v.id, v.user_id, v.photo_id
      FROM verifications v JOIN touched t ON t.user_id = v.user_id
     WHERE v.status = 3
     ORDER BY v.user_id, v.id DESC
  ), lapsed AS (
    UPDATE verifications v SET status = 6
      FROM latest l
     WHERE v.id = l.id
       AND NOT EXISTS (SELECT 1 FROM photos p
                        WHERE p.id = l.photo_id AND p.user_id = l.user_id AND p.position = 0 AND p.status = 3)
    RETURNING v.user_id
  )
  UPDATE users u SET is_verified = false
    FROM lapsed
   WHERE u.id = lapsed.user_id AND u.is_verified;
  RETURN NULL;
END;
$$;

-- (A statement trigger with transition tables cannot name columns, so it runs
-- after every UPDATE of photos; the work is a lookup per touched person.)
CREATE TRIGGER photos_verification_upd AFTER UPDATE ON photos
  REFERENCING OLD TABLE AS old_rows FOR EACH STATEMENT EXECUTE FUNCTION verification_reference_check();
CREATE TRIGGER photos_verification_del AFTER DELETE ON photos
  REFERENCING OLD TABLE AS old_rows FOR EACH STATEMENT EXECUTE FUNCTION verification_reference_check();
