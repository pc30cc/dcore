-- 0024 — Plans and store products edited in the admin panel.
--
-- plans gets what the panel edits beyond names: a short description per
-- locale, a badge, and archived_at (taken off sale for good: holders keep
-- the plan while their store subscription or grant lasts). New plans take
-- their id from an identity; the seeded ids stay. A plan is never deleted
-- (a trigger refuses it): purchases, grants, subscriptions and revenue
-- history name it, and a key is therefore never used twice.
--
-- The rank constraint becomes DEFERRABLE INITIALLY IMMEDIATE: uniqueness is
-- checked at the end of each statement instead of per row, so one UPDATE can
-- reorder every plan (swapping two ranks) without a transient duplicate.
--
-- store_purchases gets an index on product_ref: the panel asks whether a
-- product has purchases (what it grants is fixed once it has), and an
-- unindexed EXISTS would scan every purchase. The table is empty before
-- launch; after launch an index on it is built CONCURRENTLY by hand first
-- (the runner's rule), which leaves this IF NOT EXISTS with nothing to do.
--
-- The `admin` role gets `billing.catalog` (plans and store products);
-- finance holds it through `billing.*`, the owner through `*`.
--
-- Every statement can run again without effect. Nothing is rewritten: the
-- new columns have constant defaults, and the tables are small.

-- ─── plans ────────────────────────────────────────────────────────────────
ALTER TABLE plans
  ADD COLUMN IF NOT EXISTS archived_at  timestamptz,
  ADD COLUMN IF NOT EXISTS badge        smallint NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS descriptions jsonb    NOT NULL DEFAULT '{}';

ALTER TABLE plans DROP CONSTRAINT IF EXISTS plans_badge;
ALTER TABLE plans ADD CONSTRAINT plans_badge CHECK (badge BETWEEN 0 AND 3);
ALTER TABLE plans DROP CONSTRAINT IF EXISTS plans_descriptions;
ALTER TABLE plans ADD CONSTRAINT plans_descriptions CHECK (jsonb_typeof(descriptions) = 'object');
-- An archived plan is off sale, and the free plan (everyone's baseline) is never archived.
ALTER TABLE plans DROP CONSTRAINT IF EXISTS plans_archived;
ALTER TABLE plans ADD CONSTRAINT plans_archived CHECK (archived_at IS NULL OR (NOT is_active AND key <> 'free'));

DO $rank$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conrelid = 'public.plans'::regclass AND conname = 'plans_rank_key' AND condeferrable) THEN
    ALTER TABLE plans DROP CONSTRAINT IF EXISTS plans_rank_key;
    ALTER TABLE plans ADD CONSTRAINT plans_rank_key UNIQUE (rank) DEFERRABLE INITIALLY IMMEDIATE;
  END IF;
END
$rank$;

DO $identity$
BEGIN
  IF (SELECT a.attidentity FROM pg_attribute a WHERE a.attrelid = 'public.plans'::regclass AND a.attname = 'id') = '' THEN
    ALTER TABLE plans ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END
$identity$;

-- The next id follows the highest one in use (the seeds were inserted with explicit ids).
SELECT setval(pg_get_serial_sequence('public.plans', 'id'), coalesce(max(id), 0) + 1, false) FROM plans;

CREATE OR REPLACE FUNCTION plans_never_deleted() RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = public, pg_temp
AS $$
BEGIN
  RAISE EXCEPTION 'plan % is archived, never deleted', OLD.key USING ERRCODE = 'restrict_violation';
END
$$;

DROP TRIGGER IF EXISTS plans_never_deleted ON plans;
CREATE TRIGGER plans_never_deleted BEFORE DELETE ON plans FOR EACH ROW EXECUTE FUNCTION plans_never_deleted();

COMMENT ON TABLE plans IS
  'Tiers, edited in the admin panel. key: neutral, never changed and never reused (plans are archived, not deleted); free is everyone''s baseline (rank 0, never archived). rank orders upgrades (the best plan held counts); sort orders the paywall. names and descriptions: per locale (fa, en, tr); a name falls back to the active brand''s planNames for a locale the row lacks. is_active: on sale (its active store products are listed). archived_at: off sale for good; holders keep the plan while their subscription or grant lasts. badge: 0 none, 1 most popular, 2 best value, 3 new.';

COMMENT ON COLUMN plans.descriptions IS 'A short text per locale ({"fa": "...", "en": "...", "tr": "..."}) shown with the plan on the paywall.';

-- ─── store_purchases ──────────────────────────────────────────────────────
CREATE INDEX IF NOT EXISTS store_purchases_product_idx ON store_purchases (product_ref);

-- ─── The panel's permission ───────────────────────────────────────────────
INSERT INTO admin_role_permissions (role_id, permission)
SELECT r.id, 'billing.catalog' FROM admin_roles r WHERE r.key = 'admin'
ON CONFLICT DO NOTHING;

-- ─── Grants ───────────────────────────────────────────────────────────────
DO $grants$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_rw') THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO app_rw', pg_get_serial_sequence('public.plans', 'id'));
  ELSE
    RAISE NOTICE 'role app_rw does not exist: grants skipped (development database?)';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_ro') THEN
    GRANT SELECT (archived_at, badge, descriptions) ON plans TO app_ro;
  ELSE
    RAISE NOTICE 'role app_ro does not exist: grants skipped';
  END IF;
END
$grants$;
