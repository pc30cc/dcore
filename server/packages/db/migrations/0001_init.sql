-- 0001 - Foundation: extensions, identifiers, H3 cell helpers, partition machinery.
--
-- The migration runner (packages/db/src/migrate.ts) wraps every file in its
-- own transaction: no BEGIN/COMMIT here, nothing that cannot run inside a
-- transaction (no CREATE INDEX CONCURRENTLY, no VACUUM). An applied file is
-- never edited: later changes go into new numbered files.
--
-- Extensions: PostGIS is not a trusted extension, so a superuser creates it
-- in each database before the first migration (infra/dev/native.sh does that
-- for development; production does it once by hand). The statement below is
-- then a no-op that documents the dependency. Nothing else is required:
-- H3 cells are computed by the application (h3-js) and handled here with
-- plain bigint arithmetic, ids are generated by the application.

CREATE EXTENSION IF NOT EXISTS postgis;

-- ─── Identifiers ──────────────────────────────────────────────────────────
-- Every high-volume row id is a 63-bit, time-ordered integer minted by the
-- API or the worker before the row reaches PostgreSQL (write-behind needs the
-- id first; a sequence would cost a round trip and serialise writers):
--
--   bit 63      0 (ids are positive)
--   bits 22-62  milliseconds since 2026-01-01T00:00:00Z (41 bits: until 2095)
--   bits 12-21  generator id 0-1023 (a process lease in Valkey; 1023 = this database)
--   bits 0-11   sequence within the millisecond (4096 per generator per ms)
--
-- So an id carries its creation time: tables keyed by such an id keep no
-- created_at column, and time ranges are id ranges (partition bounds, "rows
-- since yesterday" = PK range scans).

CREATE FUNCTION id_epoch_ms() RETURNS bigint
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN 1767225600000;  -- 2026-01-01T00:00:00Z

COMMENT ON FUNCTION id_epoch_ms() IS
  'Epoch of every application id (ms since 1970): 2026-01-01T00:00:00Z. Never change it.';

-- The smallest id minted at or after p_ts (inclusive lower bound of p_ts).
CREATE FUNCTION id_floor(p_ts timestamptz) RETURNS bigint
  LANGUAGE sql STABLE PARALLEL SAFE STRICT
  RETURN (floor(extract(epoch FROM p_ts) * 1000)::bigint - id_epoch_ms()) << 22;

CREATE FUNCTION id_ms(p_id bigint) RETURNS bigint
  LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
  RETURN (p_id >> 22) + id_epoch_ms();

CREATE FUNCTION id_time(p_id bigint) RETURNS timestamptz
  LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
  RETURN to_timestamp(((p_id >> 22) + id_epoch_ms()) / 1000.0);

-- Ids minted by the database itself (seed rows, rare admin inserts) use the
-- reserved generator 1023, so they never collide with an application process.
CREATE SEQUENCE id_seq AS bigint MINVALUE 0 START 0 CACHE 1;

CREATE FUNCTION id_next() RETURNS bigint
  LANGUAGE sql VOLATILE PARALLEL UNSAFE
  RETURN ((floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint - id_epoch_ms()) << 22)
         | (1023::bigint << 12)
         | (nextval('id_seq') % 4096);

COMMENT ON FUNCTION id_next() IS
  'Database-side id (generator 1023). Low-volume use only: application rows get ids from the application.';

-- ─── H3 cells as bigint ───────────────────────────────────────────────────
-- An H3 cell index is a 64-bit value whose top bit is 0, so it fits bigint.
-- Layout: mode (bits 59-62, 1 = cell), resolution (bits 52-55), base cell
-- (bits 45-51), then fifteen 3-bit digits, digit r at bits 3*(15-r)..+2;
-- digits past the resolution are 7. The parent at resolution r keeps digits
-- 1..r and sets the rest to 7. Checked against h3-js 4.2.1 cellToParent on
-- 7,200 random cells.

CREATE FUNCTION h3_resolution(p_cell bigint) RETURNS integer
  LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
  RETURN ((p_cell >> 52) & 15)::integer;

CREATE FUNCTION h3_is_cell(p_cell bigint) RETURNS boolean
  LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
  RETURN p_cell > 0 AND ((p_cell >> 59) & 15) = 1 AND ((p_cell >> 56) & 7) = 0;

-- Precondition: p_res <= h3_resolution(p_cell) (callers pass 3 or 5 for r7 cells).
CREATE FUNCTION h3_parent(p_cell bigint, p_res integer) RETURNS bigint
  LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
  RETURN (p_cell & ~(15::bigint << 52))
         | (p_res::bigint << 52)
         | ((1::bigint << ((15 - p_res) * 3)) - 1);

-- ─── Partition machinery ──────────────────────────────────────────────────
-- High-volume append tables are partitioned BY RANGE (id), one partition per
-- UTC week or month; bounds are id_floor() of the period starts, so every
-- partition holds exactly the rows minted in its period. Retention is a
-- DROP of whole partitions: no DELETE, no bloat, no vacuum debt.
--
-- Partitions live in the schema `part`, on which no application role has
-- USAGE. PostgreSQL checks privileges only on the table a statement names,
-- so every read and write goes through the parent in `public` and the
-- parent's grants (including its column grants) are the only ones that
-- apply; naming a partition directly fails with "permission denied for
-- schema part". Default privileges in `public` never reach a partition.
--
-- A partition named <parent>_pYYYYMMDD starts on that UTC date. There is no
-- DEFAULT partition on purpose: a row outside every partition fails loudly
-- instead of landing in a table that would have to be scanned before every
-- future partition could be attached.
--
-- Locks: partitions are created ahead as standalone tables and then
-- ATTACHed, which takes SHARE UPDATE EXCLUSIVE on the parent and never waits
-- for or blocks reads and writes. Dropping one needs ACCESS EXCLUSIVE on the
-- parent; partition_drop_expired() (0009) drops one partition per call with
-- a 200 ms lock_timeout, so a reader that holds the parent delays the drop,
-- never the traffic behind it for longer than that.

CREATE SCHEMA part;
REVOKE ALL ON SCHEMA part FROM PUBLIC;

COMMENT ON SCHEMA part IS
  'Partitions of the tables registered in partitioned_tables. No application role has USAGE: access goes through the parent tables in public.';

CREATE TABLE partitioned_tables (
  parent      text     PRIMARY KEY CHECK (parent ~ '^[a-z][a-z0-9_]*$'),
  period      text     NOT NULL CHECK (period IN ('week', 'month')),
  premake     smallint NOT NULL DEFAULT 3 CHECK (premake BETWEEN 1 AND 12),
  retention   interval CHECK (retention IS NULL OR retention >= interval '7 days'),
  reloptions  text[]   NOT NULL DEFAULT '{}'
);

COMMENT ON TABLE partitioned_tables IS
  'Registry for partitions_maintain() and partition_drop_expired(): period, how many periods to create ahead, retention (NULL keeps every partition) and the storage parameters each new partition gets (partitioned parents cannot carry them).';

CREATE FUNCTION partition_period_start(p_period text, p_ts timestamptz) RETURNS timestamptz
  LANGUAGE sql STABLE PARALLEL SAFE STRICT
  RETURN date_trunc(p_period, p_ts AT TIME ZONE 'UTC') AT TIME ZONE 'UTC';

CREATE FUNCTION partition_period_length(p_period text) RETURNS interval
  LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
  RETURN CASE p_period WHEN 'week' THEN interval '1 week' WHEN 'month' THEN interval '1 month' END;

-- Creates the partition of p_parent that holds p_ts, if it does not exist,
-- and returns its name. The table is created with the parent's columns,
-- defaults and CHECK constraints, then attached (indexes are created on the
-- empty table by the ATTACH).
CREATE FUNCTION partition_create(p_parent text, p_ts timestamptz) RETURNS text
  LANGUAGE plpgsql
  SET search_path = public, pg_temp
AS $$
DECLARE
  v_reg   partitioned_tables;
  v_from  timestamptz;
  v_to    timestamptz;
  v_name  text;
  v_with  text := '';
BEGIN
  SELECT * INTO STRICT v_reg FROM partitioned_tables WHERE parent = p_parent;
  v_from := partition_period_start(v_reg.period, p_ts);
  -- Add the length in UTC so a month is a calendar month whatever the session's TimeZone.
  v_to := ((v_from AT TIME ZONE 'UTC') + partition_period_length(v_reg.period)) AT TIME ZONE 'UTC';
  v_name := format('%s_p%s', p_parent, to_char(v_from AT TIME ZONE 'UTC', 'YYYYMMDD'));
  IF to_regclass(format('part.%I', v_name)) IS NOT NULL THEN
    RETURN v_name;
  END IF;
  IF cardinality(v_reg.reloptions) > 0 THEN
    v_with := format(' WITH (%s)', array_to_string(v_reg.reloptions, ', '));
  END IF;
  EXECUTE format('CREATE TABLE part.%I (LIKE public.%I INCLUDING DEFAULTS INCLUDING CONSTRAINTS)%s',
                 v_name, p_parent, v_with);
  EXECUTE format('ALTER TABLE public.%I ATTACH PARTITION part.%I FOR VALUES FROM (%s) TO (%s)',
                 p_parent, v_name, id_floor(v_from), id_floor(v_to));
  RETURN v_name;
END;
$$;

-- The upper bound (exclusive id) of a range partition, read from the catalog.
CREATE FUNCTION partition_upper_id(p_partition regclass) RETURNS bigint
  LANGUAGE sql STABLE PARALLEL SAFE STRICT
  RETURN (regexp_match(pg_get_expr((SELECT relpartbound FROM pg_class WHERE oid = p_partition), p_partition),
                       'TO \(''?(-?[0-9]+)''?\)'))[1]::bigint;

-- Creates the current period and `premake` periods ahead for one registered
-- table. Idempotent and safe at any time. The worker calls it once per
-- parent, each call its own statement (autocommit), so the locks of one
-- parent are released before the next one is touched. ATTACH does not
-- conflict with reads or writes; the 200 ms lock_timeout only bounds a wait
-- behind DDL or a VACUUM of the parent, after which the period is reported
-- `ensure_deferred` and made by a later run (periods are made `premake`
-- ahead, so a deferred run loses nothing).
-- SECURITY DEFINER: the maintenance role may call it without owning the tables.
CREATE FUNCTION partitions_maintain(p_parent text) RETURNS TABLE (action text, partition_name text)
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = public, pg_temp
  SET lock_timeout = '200ms'
AS $$
DECLARE
  v_reg partitioned_tables;
  v_i   integer;
BEGIN
  SELECT * INTO STRICT v_reg FROM partitioned_tables WHERE parent = p_parent;
  FOR v_i IN 0 .. v_reg.premake LOOP
    BEGIN
      action := 'ensure';
      partition_name := partition_create(v_reg.parent,
                          ((now() AT TIME ZONE 'UTC') + v_i * partition_period_length(v_reg.period)) AT TIME ZONE 'UTC');
    EXCEPTION WHEN lock_not_available THEN
      action := 'ensure_deferred';
      partition_name := v_reg.parent;
    END;
    RETURN NEXT;
  END LOOP;
END;
$$;

REVOKE ALL ON FUNCTION partitions_maintain(text) FROM PUBLIC;
REVOKE ALL ON FUNCTION partition_create(text, timestamptz) FROM PUBLIC;
